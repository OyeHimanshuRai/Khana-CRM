<?php

namespace App\Console\Commands;

use App\Models\RecipeItem;
use App\Models\Shop;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;

/**
 * Copy one branch's recipes to another branch of the same company.
 *
 * A recipe belongs to the branch that cooks it, so a new outlet starts with
 * none and consumes no ingredients until somebody writes them. For a chain
 * whose branches cook the same menu that is a lot of typing; this carries the
 * recipes across in one step.
 *
 * A dish the target already has a recipe for is left alone unless
 * --overwrite is given, so running it twice, or after somebody tuned one
 * branch's quantities, never undoes their work.
 */
class CopyRecipes extends Command
{
    protected $signature = 'recipes:copy
                            {from : Id of the branch to copy from}
                            {to : Id of the branch to copy to}
                            {--overwrite : Replace the recipe of a dish the target branch already has}';

    protected $description = 'Copy the recipes of one branch to another branch of the same company';

    public function handle(): int
    {
        $from = Shop::query()->withoutGlobalScopes()->find((int) $this->argument('from'));
        $to = Shop::query()->withoutGlobalScopes()->find((int) $this->argument('to'));

        if (! $from || ! $to) {
            $this->error('Both branch ids must exist.');

            return self::FAILURE;
        }

        if ($from->id === $to->id) {
            $this->error('Choose two different branches.');

            return self::FAILURE;
        }

        if ($from->tenant_id !== $to->tenant_id) {
            $this->error('Recipes can only be copied between branches of the same company.');

            return self::FAILURE;
        }

        $copied = 0;
        $dishes = 0;
        $skipped = 0;

        DB::transaction(function () use ($from, $to, &$copied, &$dishes, &$skipped) {
            $source = RecipeItem::allShops()->where('shop_id', $from->id)->orderBy('product_id')->orderBy('sort_order')->get()->groupBy('product_id');

            foreach ($source as $dishId => $rows) {
                $has = RecipeItem::allShops()->where('shop_id', $to->id)->where('product_id', $dishId)->exists();

                if ($has && ! $this->option('overwrite')) {
                    $skipped++;

                    continue;
                }

                if ($has) {
                    RecipeItem::allShops()->where('shop_id', $to->id)->where('product_id', $dishId)->delete();
                }

                foreach ($rows as $row) {
                    // variant_key is generated by the database; writing it is an error on MySQL.
                    $copy = $row->replicate(['shop_id', 'variant_key']);
                    $copy->shop_id = $to->id;
                    $copy->save();
                    $copied++;
                }

                $dishes++;
            }
        });

        $this->info(sprintf(
            'Copied %d ingredient line(s) for %d dish(es) from "%s" to "%s"; %d dish(es) already had a recipe and were left alone.',
            $copied, $dishes, $from->name, $to->name, $skipped,
        ));

        return self::SUCCESS;
    }
}
